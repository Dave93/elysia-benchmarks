/**
 * The fact set for the Elysia vs Express article, from the result files only — never from prose.
 * Output: results/express-facts.md and results/express-facts.json.
 *
 * Aggregation copies bench/report.ts: median of VALID windows, success rps = measurement.successRps.
 * Ratios are ratios of the unrounded medians; display values are rounded last. "Rounds won" compares the
 * two configurations inside the same round, so a ratio carried by one round shows up as 2 of 3 or worse.
 *
 * Four configurations, three one-variable steps:
 *   runtime   X-node   → X-bun-pg  (same file, same postgres.js driver; Node 26 vs Bun 1.4)
 *   driver    X-bun-pg → X-bun     (Express on Bun; postgres.js vs Bun SQL)
 *   framework X-bun    → E         (Bun SQL on Bun; Express 5.3 vs Elysia 2)
 *
 *   bun bench/article-facts-express.ts [results/full-express-<date>.json] [results/noise-express-<date>.json]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { median } from "./metrics";

const [fullPath = "results/full-express-2026-11-09.json", noisePath = "results/noise-express-2026-11-09.json"] = process.argv.slice(2);
const FULL = JSON.parse(readFileSync(fullPath, "utf8"));
let NOISE: any = null;
try { NOISE = JSON.parse(readFileSync(noisePath, "utf8")); } catch { /* reported below */ }

type Run = {
  round: number; config: string; case: string; concurrency: number; valid: boolean;
  measurement?: { successRps: number; latMs: { p50: number; p99: number }; resources?: { summary: { cpuCores: number | null; rssMeanMb: number | null } }; foreignCpu?: { mean: number }; pgCheckpoints?: { timed: number; requested: number } };
  contendedAttempts?: unknown[];
};
const runs: Run[] = FULL.runs;
const CONFIGS = ["E", "X-bun", "X-bun-pg", "X-node"] as const;
const CONC = [10, 100, 500];
const ROUTES = [
  { id: "health", label: "GET /health", db: false },
  { id: "echo", label: "POST /echo", db: false },
  { id: "me", label: "GET /me", db: true },
  { id: "user", label: "GET /users/:id", db: true },
  { id: "list", label: "GET /users (list)", db: true },
  { id: "order", label: "POST /orders", db: true },
  { id: "cpu", label: "GET /cpu", db: false },
];

const windows = (config: string, kase: string, c: number) =>
  runs.filter((r) => r.valid && r.config === config && r.case === kase && r.concurrency === c).sort((a, b) => a.round - b.round);

function cell(config: string, kase: string, c: number) {
  const w = windows(config, kase, c);
  if (w.length !== FULL.methodology.repeats) throw new Error(`${config}/${kase}/c=${c}: ${w.length} valid windows, expected ${FULL.methodology.repeats}`);
  const rps = w.map((x) => x.measurement!.successRps);
  const cores = w.map((x) => x.measurement!.resources?.summary.cpuCores).filter((v): v is number => typeof v === "number");
  return {
    rps: median(rps),
    byRound: new Map(w.map((x) => [x.round, x.measurement!.successRps])),
    spreadPct: ((Math.max(...rps) - Math.min(...rps)) / Math.min(...rps)) * 100,
    p50: median(w.map((x) => x.measurement!.latMs.p50)),
    p99: median(w.map((x) => x.measurement!.latMs.p99)),
    cores: cores.length === w.length ? median(cores) : null,
    perCpuSecond: cores.length === w.length ? median(w.map((x) => x.measurement!.successRps / x.measurement!.resources!.summary.cpuCores!)) : null,
    rssMb: median(w.map((x) => x.measurement!.resources?.summary.rssMeanMb ?? NaN)),
  };
}
const wins = (a: ReturnType<typeof cell>, b: ReturnType<typeof cell>) => {
  let n = 0;
  for (const [round, v] of a.byRound) if (v > (b.byRound.get(round) ?? Infinity)) n++;
  return n;
};

const f0 = (n: number) => Math.round(n).toLocaleString("en-US");
const f1 = (n: number) => n.toLocaleString("en-US", { minimumFractionDigits: 1, maximumFractionDigits: 1 });
const f2 = (n: number) => n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const pct = (ratio: number) => `${ratio >= 1 ? "+" : ""}${f1((ratio - 1) * 100)}%`;

// Noise floor: E, c=100, five back-to-back windows per route (bench/noise.ts).
const noise = NOISE ? ["health", "user"].map((id) => {
  const v = NOISE.runs.filter((r: Run) => r.valid && r.config === "E" && r.case === id && r.concurrency === 100)
    .sort((a: Run, b: Run) => a.round - b.round).map((r: Run) => r.measurement!.successRps);
  return { id, values: v, spreadPct: v.length > 1 ? ((Math.max(...v) - Math.min(...v)) / Math.min(...v)) * 100 : null };
}) : null;

const json: any = { source: fullPath, noiseSource: NOISE ? noisePath : null, status: FULL.status, startedAt: FULL.startedAt, finishedAt: FULL.finishedAt, routes: {} };
const md: string[] = [];
md.push(`# Elysia vs Express — generated fact set`, "");
md.push(`Generated by \`bun bench/article-facts-express.ts\` from \`${fullPath}\`${NOISE ? ` and \`${noisePath}\`` : ""}. Do not edit by hand.`, "");
md.push(`Run status: **${FULL.status}**, started ${FULL.startedAt}, finished ${FULL.finishedAt ?? "—"}. Windows: ${runs.filter((r) => r.valid).length} valid of ${runs.length} recorded; quick preflight ${FULL.quickPreflight.filter((r: Run) => r.valid).length}/${FULL.quickPreflight.length}. Contended attempts re-measured: ${runs.reduce((s, r) => s + (r.contendedAttempts?.length ?? 0), 0)}.`, "");
const resumed = FULL.methodology.resumedFrom;
if (resumed) {
  const prior = JSON.parse(readFileSync(resumed.path, "utf8"));
  const failed = prior.runs.filter((r: Run) => !r.valid);
  md.push(`Resumed from \`${resumed.path}\` (started ${resumed.startedAt}, status ${prior.status}): ${resumed.carriedValidWindows} valid windows carried over; re-measured in this file: ${runs.length - resumed.carriedValidWindows}. Failed windows kept in that file:`);
  for (const r of failed as any[]) {
    const raw = r.measurement?.raw?.result ?? {};
    md.push(`- ${r.config}/${r.case}/c=${r.concurrency} round ${r.round}: ${r.issues.join("; ")}; ${raw.req2xx} 2xx; bombardier error ${JSON.stringify(raw.errors)}; success req/s ${r.measurement?.successRps?.toFixed(1)}; p99 ${(r.measurement?.latMs?.p99 / 1000).toFixed(2)} s, max ${(r.measurement?.latMs?.max / 1000).toFixed(2)} s`);
  }
  md.push("");
}
md.push(`Method: ${FULL.methodology.repeats} rounds × ${FULL.methodology.cases.length} routes × c=${FULL.methodology.concurrencies.join("/")}, warmup ${FULL.methodology.warmup}, window ${FULL.methodology.duration}; round orders ${JSON.stringify(FULL.methodology.roundOrders)}. Parity: ${FULL.parity?.passed === true ? `passed, ${FULL.parity.checks} checks × ${FULL.parity.configs.length} configs` : "NOT recorded"}.`, "");
const fc = runs.filter((r) => r.valid).map((r) => r.measurement!.foreignCpu?.mean ?? NaN).filter(Number.isFinite);
md.push(`Foreign CPU during measured windows (100 = one core): median ${f0(median(fc))}%, max ${f0(Math.max(...fc))}%. Gate: ${FULL.env?.contentionGatePct}%.`, "");
const env = FULL.env ?? {};
md.push(`Environment: ${env.linux?.cpuModel ?? env.cpu}, ${env.linux?.logicalCpus ?? env.cores} logical CPUs, ${env.linux?.os ?? env.macos}, kernel ${env.linux?.kernel ?? "—"}, governor ${env.linux?.cpuGovernor ?? "—"}; Bun ${env.bun}; Node ${env.node}; ${env.postgresServer}; bombardier sha256 ${env.bombardierSha256}; orders autovacuum ${env.ordersAutovacuum}.`, "");
md.push(`Express manifest: ${JSON.stringify(env.expressManifest?.dependencies ?? null)}. Elysia manifest: ${JSON.stringify(env.elysiaManifest?.dependencies ?? null)}.`, "");
md.push("Configurations:", ...FULL.methodology.configs.map((c: any) => `- ${c.id}: ${c.label} — \`${c.cmd.join(" ")}\``), "");

if (noise) {
  md.push(`## Noise floor (E, c=100, 5 back-to-back 30 s windows)`, "");
  for (const n of noise) md.push(`- ${n.id}: ${n.values.map(f0).join(", ")} req/s; spread (max−min)/min = ${n.spreadPct === null ? "—" : f1(n.spreadPct) + "%"}`);
  md.push("");
} else md.push(`## Noise floor`, "", `No noise file at ${noisePath}.`, "");

md.push(`## Throughput, median successful req/s of 3 rounds`, "");
md.push(`| route | c | E (Elysia/Bun, Bun SQL) | X-bun (Express/Bun, Bun SQL) | X-bun-pg (Express/Bun, postgres.js) | X-node (Express/Node, postgres.js) | max round spread |`);
md.push(`|---|---:|---:|---:|---:|---:|---:|`);
for (const r of ROUTES) for (const c of CONC) {
  const cells = Object.fromEntries(CONFIGS.map((id) => [id, cell(id, r.id, c)])) as Record<(typeof CONFIGS)[number], ReturnType<typeof cell>>;
  md.push(`| ${r.label} | ${c} | ${CONFIGS.map((id) => f0(cells[id].rps)).join(" | ")} | ${f1(Math.max(...CONFIGS.map((id) => cells[id].spreadPct)))}% |`);
  json.routes[`${r.id}/${c}`] = Object.fromEntries(CONFIGS.map((id) => [id, { rps: cells[id].rps, spreadPct: cells[id].spreadPct, p50: cells[id].p50, p99: cells[id].p99, cores: cells[id].cores, perCpuSecond: cells[id].perCpuSecond, rssMb: cells[id].rssMb, byRound: Object.fromEntries(cells[id].byRound) }]));
}
md.push("");

md.push(`## The three steps, ratio of medians (rounds the faster side won, of 3)`, "");
md.push(`| route | c | runtime: X-bun-pg ÷ X-node | driver: X-bun ÷ X-bun-pg | framework: E ÷ X-bun | overall: E ÷ X-node |`);
md.push(`|---|---:|---:|---:|---:|---:|`);
for (const r of ROUTES) for (const c of CONC) {
  const e = cell("E", r.id, c), xb = cell("X-bun", r.id, c), xp = cell("X-bun-pg", r.id, c), xn = cell("X-node", r.id, c);
  const step = (a: ReturnType<typeof cell>, b: ReturnType<typeof cell>) => {
    const ratio = a.rps / b.rps;
    return `${f2(ratio)}× (${pct(ratio)}; ${ratio >= 1 ? wins(a, b) : wins(b, a)}/3)`;
  };
  md.push(`| ${r.label} | ${c} | ${step(xp, xn)} | ${r.db ? step(xb, xp) : `${step(xb, xp)} — no DB on this route`} | ${step(e, xb)} | ${step(e, xn)} |`);
}
md.push("");

md.push(`## Latency, median of 3 rounds (ms)`, "");
md.push(`| route | c | ${CONFIGS.map((id) => `${id} p50 / p99`).join(" | ")} |`);
md.push(`|---|---:|${CONFIGS.map(() => "---:").join("|")}|`);
for (const r of ROUTES) for (const c of CONC) {
  md.push(`| ${r.label} | ${c} | ${CONFIGS.map((id) => { const x = cell(id, r.id, c); return `${f2(x.p50)} / ${f2(x.p99)}`; }).join(" | ")} |`);
}
md.push("");

md.push(`## Server process CPU and memory, median of 3 rounds`, "");
md.push(`Tree CPU cores = CPU-seconds the server's process tree used ÷ window span (Postgres and the load generator excluded). Per CPU-second = successful requests per CPU-second of the server tree. RSS = mean resident memory of the tree during the window.`, "");
md.push(`| route | c | ${CONFIGS.map((id) => `${id} cores / req per CPU-s / RSS MiB`).join(" | ")} |`);
md.push(`|---|---:|${CONFIGS.map(() => "---:").join("|")}|`);
for (const r of ROUTES) for (const c of CONC) {
  md.push(`| ${r.label} | ${c} | ${CONFIGS.map((id) => { const x = cell(id, r.id, c); return `${x.cores === null ? "—" : f2(x.cores)} / ${x.perCpuSecond === null ? "—" : f0(x.perCpuSecond)} / ${f0(x.rssMb)}`; }).join(" | ")} |`);
}
md.push("");

const cp = runs.filter((r) => r.valid && ((r.measurement?.pgCheckpoints?.timed ?? 0) + (r.measurement?.pgCheckpoints?.requested ?? 0)) > 0);
md.push(`## Postgres checkpoints inside measured windows`, "", cp.length ? cp.map((r) => `- ${r.config}/${r.case}/c=${r.concurrency} round ${r.round}: ${JSON.stringify(r.measurement!.pgCheckpoints)}`).join("\n") : "None.", "");

writeFileSync("results/express-facts.md", md.join("\n") + "\n");
writeFileSync("results/express-facts.json", JSON.stringify(json, null, 2) + "\n");
console.log("wrote results/express-facts.md and results/express-facts.json");
